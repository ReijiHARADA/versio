#!/usr/bin/env node
/**
 * Generates src/styles/squircle.css: 9-slice SVG masks for clothoid (G2)
 * rounded corners, one fill + one 1px ring per radius.
 *
 * Corner: clothoid (curvature linear 0 → 1/R) + circular arc + mirrored
 * clothoid, 60% of the turn in transitions. It starts K·r from the corner so
 * a nominal radius r reads like the iOS continuous corner of the same r.
 *
 * Run: node scripts/generate-squircle-css.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const K = 1.52866483;
// SVG masks are rasterized at intrinsic size; draw them 4x so the 9-slice stays crisp on Retina.
const SCALE = 4;
const TRANSITION = 0.6;
const RADII = [2, 3, 4, 6, 8, 10, 11, 12, 16];
const TOKENS = { sm: 4, md: 8, lg: 12, card: 10, control: 8, "control-inner": 6 };

/** Unit corner from (-1,0) on the top edge to (0,1) on the right edge; corner at origin, y down. */
export function clothoidCorner(samples = 16) {
  const tc = (Math.PI / 4) * TRANSITION;
  const L = 2 * tc;
  const La = Math.PI / 2 - 2 * tc;
  const T = 2 * L + La;
  const kappa = (s) => (s < L ? s / L : s < L + La ? 1 : (T - s) / L);
  const N = 4000;
  const ds = T / N;
  let x = 0;
  let y = 0;
  let phi = 0;
  const raw = [];
  for (let i = 0; i < N; i++) {
    const s = (i + 0.5) * ds;
    const mid = phi + (kappa(s) * ds) / 2;
    x += Math.cos(mid) * ds;
    y += Math.sin(mid) * ds;
    phi += kappa(s) * ds;
    if ((i + 1) % (N / samples) === 0) raw.push([x, y]);
  }
  return raw.map(([px, py]) => [(px - x) / x, py / x]);
}

const UNIT = clothoidCorner();
const f = (v) => +v.toFixed(2);

/** Closed path of a rect [x0,y0]-[x1,y1] with clothoid corners of nominal radius r. */
export function roundedRectPath(x0, y0, x1, y1, r) {
  const e = K * r;
  const corners = [
    ([ux, uy]) => [x1 + ux * e, y0 + uy * e],
    ([ux, uy]) => [x1 - uy * e, y1 + ux * e],
    ([ux, uy]) => [x0 - ux * e, y1 - uy * e],
    ([ux, uy]) => [x0 + uy * e, y0 - ux * e],
  ];
  const pts = corners.flatMap((map) => UNIT.map(map));
  return `M${f(x0 + e)} ${f(y0)}` + pts.map(([x, y]) => `L${f(x)} ${f(y)}`).join("") + "Z";
}

function svgUrl(size, body) {
  const svg = `<svg xmlns='http://www.w3.org/2000/svg' width='${size * SCALE}' height='${size * SCALE}' viewBox='0 0 ${size} ${size}'>${body}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg).replace(/%20/g, " ").replace(/%3D/g, "=").replace(/%3A/g, ":").replace(/%2F/g, "/").replace(/%27/g, "'")}")`;
}

function masks(r) {
  const slice = Math.ceil(K * r);
  // A 2px centre makes WebKit thicken stretched edges; 16px keeps them 1px.
  const size = slice * 2 + 16;
  const fill = svgUrl(size, `<path d='${roundedRectPath(0, 0, size, size, r)}'/>`);
  const ring = svgUrl(
    size,
    `<path d='${roundedRectPath(0.5, 0.5, size - 0.5, size - 0.5, Math.max(r - 0.5, 0.5))}' fill='none' stroke='black'/>`
  );
  const cut = slice * SCALE; // WebKit reads slice in the SVG's intrinsic pixels
  return { fill: `${fill} ${cut} / ${slice}px`, ring: `${ring} ${cut} / ${slice}px` };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const lines = [
    "/* Generated by scripts/generate-squircle-css.mjs — do not edit by hand. */",
    "/* Clothoid (G2) corner masks for -webkit-mask-box-image; see squircle.module.css. */",
    "",
    "@property --sq-bg { syntax: '<color>'; inherits: true; initial-value: transparent; }",
    "@property --sq-line { syntax: '<color>'; inherits: true; initial-value: transparent; }",
    "",
    ":root {",
  ];
  for (const r of RADII) {
    const { fill, ring } = masks(r);
    // Circle of radius K·r stays inside the clothoid: host border-radius for box-shadow / outline.
    lines.push(`  --sq-fill-${r}: ${fill};`, `  --sq-ring-${r}: ${ring};`, `  --sq-radius-${r}: ${(K * r).toFixed(2)}px;`);
  }
  for (const [name, r] of Object.entries(TOKENS)) {
    lines.push(`  --sq-fill-${name}: var(--sq-fill-${r});`, `  --sq-ring-${name}: var(--sq-ring-${r});`, `  --sq-radius-${name}: var(--sq-radius-${r});`);
  }
  lines.push("}", "");
  const out = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/styles/squircle.css");
  fs.writeFileSync(out, lines.join("\n"));
  console.log(`wrote ${path.relative(process.cwd(), out)}`);
}
