#!/usr/bin/env node
// Paper tab caps (src/components/shell/paperTabShape.ts): clothoid top corners plus the
// concave flares that join the active tab to the main card. Run after changing the sizes.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { clothoidCorner, K } from "./generate-squircle-css.mjs";

const HEIGHT = 41; // titlebar-h (50) - card-gap (10) + the 1px overlap onto the card
const CORNER_R = 10; // top corners, same as --sq-radius-card
const FLARE_R = 7; // concave joint to the card

const UNIT = clothoidCorner();
const e = K * CORNER_R;
const ef = K * FLARE_R;
const W = Math.ceil(ef + e);
const f = (v) => +v.toFixed(2);

function outline() {
  // Flare: bottom-right corner of the gap left of the tab, corner at (ef, HEIGHT).
  const flare = UNIT.map(([ux, uy]) => [ef + ux * ef, HEIGHT - uy * ef]);
  // Top-left corner of the tab, corner at (ef, 0).
  const top = UNIT.map(([ux, uy]) => [ef + uy * e, -ux * e]);
  return [[0, HEIGHT], ...flare, [ef, e], ...top, [W, 0]];
}

const pts = outline();
const toPath = (list, mirror) =>
  list.map(([x, y], i) => `${i ? "L" : "M"}${f(mirror ? W - x : x)} ${f(y)}`).join("");
// The stroke sits half a pixel inside the fill so the 1px line stays crisp.
const strokePts = pts.map(([x, y]) => [x + (x < W ? 0.5 : 0) * (y < HEIGHT ? 1 : 0), y + (y === 0 ? 0.5 : 0)]);

// Flush variant for the first tab when it lines up with the card's left edge: no flare, and
// the side runs DROP px past the tab into the card, squaring off the card's top-left corner.
const DROP = Math.ceil(e) + 1;
const flushTop = UNIT.map(([ux, uy]) => [uy * e, -ux * e]);
const FW = Math.ceil(e);
const flush = [[0, HEIGHT + DROP], [0, e], ...flushTop, [FW, 0]];
const flushStroke = flush.map(([x, y]) => [x === 0 ? 0.5 : x, y === 0 ? 0.5 : y]);

const out = `// Generated by scripts/generate-tab-shape.mjs. Do not edit by hand.
export const TAB_HEIGHT = ${HEIGHT};
export const TAB_CAP_WIDTH = ${W};
export const TAB_FLARE = ${f(ef)};
export const TAB_CAP_LEFT_FILL = "${toPath(pts, false)}L${W} ${HEIGHT}Z";
export const TAB_CAP_RIGHT_FILL = "${toPath(pts, true)}L0 ${HEIGHT}Z";
export const TAB_FLUSH_DROP = ${DROP};
export const TAB_FLUSH_CAP_WIDTH = ${FW};
export const TAB_FLUSH_LEFT_FILL = "${toPath(flush, false)}L${FW} ${HEIGHT + DROP}Z";
export const TAB_FLUSH_LEFT_STROKE = "${toPath(flushStroke, false)}";
export const TAB_CAP_LEFT_STROKE = "${toPath(strokePts, false)}";
export const TAB_CAP_RIGHT_STROKE = "${toPath(strokePts, true)}";
`;
const file = path.join(path.dirname(fileURLToPath(import.meta.url)), "../src/components/shell/paperTabShape.ts");
fs.writeFileSync(file, out);
console.log(`wrote ${path.relative(process.cwd(), file)}`);
